import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(new URL('../apps/api/package.json', import.meta.url));
const { build } = require('esbuild');
const directory = path.join(root, 'supabase/functions/easy-latex-api');
const dependencies = ['pg', 'zod', '@supabase/supabase-js'];
const imports = Object.fromEntries(dependencies.map(name => [name, `npm:${name}@${require(`${name}/package.json`).version}`]));
await mkdir(directory, {recursive: true});
await build({
  absWorkingDir: root, entryPoints: ['apps/api/src/supabase-runtime.ts'],
  outfile: path.join(directory, 'backend.generated.js'), bundle: true, format: 'esm',
  platform: 'node', target: 'es2022', external: dependencies,
  inject: ['scripts/edge-globals.ts'], sourcemap: false, legalComments: 'none',
  banner: {js: '// Generated by npm run supabase:build. Edit apps/api/src instead.'},
});
await writeFile(path.join(directory, 'deno.json'), JSON.stringify({imports, compilerOptions: {lib: ['deno.ns', 'dom', 'dom.iterable', 'esnext']}}, null, 2) + '\n');
// Build checks catch accidental imports of a server/worker or local secret paths.
const bundle = await readFile(path.join(directory, 'backend.generated.js'), 'utf8');
for (const forbidden of ['node:child_process', 'node:fs', 'fastify', '.env.local']) {
  if (bundle.includes(forbidden)) throw new Error(`Edge bundle unexpectedly contains ${forbidden}`);
}
console.log('Supabase Edge backend built with pinned npm dependencies; no environment files are bundled.');
