import { describe, expect, it } from 'vitest';
import { escapeLatex, parseInline, parseVisualDocument, replaceVisualRange } from '../src/parser/visualDocument';

const project = String.raw`% Document generated by an agent
\documentclass{article}
\newcommand{\custom}[1]{\textbf{#1}}
\title{A document}
\begin{document}
\maketitle

\section{Introduction}
Hello \textbf{beautiful \emph{world}}. A citation \cite[2]{key} and $x^2$.

\begin{itemize}
\item First item
\item Second \textit{item}
\end{itemize}

\begin{figure}[ht]
\centering
\includegraphics[width=.8\textwidth]{figures/a.png}
\caption{A {nested} caption}
\end{figure}

\section*{Conclusion}
Thank you.
\end{document}
% Keep this exact trailing comment
`;

describe('lossless visual document projection', () => {
  it('projects headings, rich paragraphs and lists without including the preamble', () => {
    const result = parseVisualDocument(project);
    expect(result.complete).toBe(true);
    expect(result.blocks.map(block => block.kind)).toEqual(['protected', 'heading', 'paragraph', 'item', 'item', 'protected', 'heading', 'paragraph']);
    const heading = result.blocks[1]!;
    expect(project.slice(heading.contentFrom, heading.contentTo)).toBe('Introduction');
    expect(result.blocks[6]?.command).toBe('section*');
    expect(result.bodyTo).toBe(project.indexOf('\\end{document}'));
  });
  it('patches exactly one range while preserving macros, preamble, other blocks and trailing comments', () => {
    const result = parseVisualDocument(project);
    const paragraph = result.blocks[2]!;
    const next = replaceVisualRange(project, paragraph.contentFrom, paragraph.contentTo, escapeLatex('Nội dung mới: 100% & $5.'));
    expect(next.slice(0, paragraph.contentFrom)).toBe(project.slice(0, paragraph.contentFrom));
    expect(next.slice(paragraph.contentFrom + escapeLatex('Nội dung mới: 100% & $5.').length)).toBe(project.slice(paragraph.contentTo));
    expect(next).toContain('100\\% \\& \\$5.');
  });
  it('retains every byte when inline nodes are concatenated', () => {
    const examples = [String.raw`Hello \textbf{nested \emph{text}} and \cite[p.~2]{a,b}.`, String.raw`100\% \& \$5 \_ \{x\} \textbackslash{} ~end.`, 'A % comment\nB', String.raw`$a + b$ and \(c\) and \custom[option]{nested {group}}`, String.raw`\verb|{not a group}|`];
    for (const source of examples) expect(parseInline(source).map(node => node.source).join('')).toBe(source);
  });
  it('ignores commented boundaries and verbatim content', () => {
    const source = String.raw`\documentclass{article}
% \begin{document}
\newcommand{\example}{\begin{document}}
\begin{document}
Before.

\begin{verbatim}
\end{document}
\section{Not a heading}
\end{verbatim}

After.
\end{document}`;
    const result = parseVisualDocument(source);
    expect(result.blocks.map(block => block.kind)).toEqual(['paragraph', 'protected', 'paragraph']);
    expect(source.slice(result.blocks[2]!.from, result.blocks[2]!.to)).toBe('After.');
  });
  it('keeps document boundaries inside inline verbatim and escaped currency intact', () => {
    const source = '\\begin{document}\n\\verb|\\end{document}|\n\n\\begin{quote}Cost: \\$5.\\end{quote}\n\nAfter.\n\\end{document}';
    const result = parseVisualDocument(source);
    expect(result.complete).toBe(true);
    expect(source.slice(result.blocks.at(-1)!.from, result.blocks.at(-1)!.to)).toBe('After.');
  });
  it('protects malformed environments and incomplete document setup', () => {
    expect(parseVisualDocument('\\documentclass{article}').complete).toBe(false);
    const result = parseVisualDocument('\\begin{document}\n\\begin{figure}\nUnfinished');
    expect(result.complete).toBe(false);
    expect(result.blocks[0]?.kind).toBe('protected');
    expect(result.blocks[0]?.to).toBe(result.bodyTo);
  });
  it('supports included body fragments and preserves nested environments as one block', () => {
    const source = String.raw`\section{Included chapter}
Some text.

\begin{itemize}
\item Outer
\begin{enumerate}
\item Inner
\end{enumerate}
\end{itemize}`;
    expect(parseVisualDocument(source).blocks.map(block => block.kind)).toEqual(['heading', 'paragraph', 'protected']);
  });
  it('does not split inside multiline groups, inline math or escaped commands', () => {
    const source = String.raw`Text \textbf{across

blank lines} and $a

+b$.

Next paragraph.`;
    expect(parseVisualDocument(source).blocks.map(block => block.kind)).toEqual(['paragraph', 'paragraph']);
  });
  it('protects macro definitions rather than treating them as editable prose', () => {
    expect(parseVisualDocument(String.raw`\def\foo#1{#1}
A line.`).blocks[0]?.kind).toBe('protected');
  });
});
